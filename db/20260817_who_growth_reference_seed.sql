-- ============================================================================
-- 20260817_who_growth_reference_seed.sql
-- Seeds who_weight_for_age, who_height_for_age, who_weight_for_height with the
-- official WHO Child Growth Standards LMS reference tables (2006).
--
-- WHY THIS MIGRATION EXISTS (read before touching who_calculator.php):
-- These three tables were declared in schema.sql with a comment claiming they
-- were 'seeded from official WHO tables', but no seed data was ever written.
-- Every lookup was silently falling through to who_fallback_reference() in
-- who_calculator.php -- a made-up linear approximation, NOT WHO data. That
-- means every WAZ/HAZ/WHZ z-score and every nutritional_status classification
-- computed by this app before this migration was fabricated, not clinical.
--
-- Source: WHO Child Growth Standards, official z-score tables (L/M/S columns),
-- https://www.who.int/tools/child-growth-standards/standards
--   - Weight-for-age: 0-60 months, boys + girls
--   - Length/height-for-age: 0-24 months uses recumbent LENGTH tables,
--     24-60 months uses standing HEIGHT tables (WHO's own convention).
--   - Weight-for-length/height: 45.0-64.5 cm uses the birth-2y recumbent
--     LENGTH table (no standing-height table exists below 65cm); 65.0-120.0
--     cm uses the 2-5y standing HEIGHT table. NOTE: WHO publishes weight-for-
--     length and weight-for-height as two separate curves that legitimately
--     disagree over the 65-110cm range they both cover, because the correct
--     one to use depends on whether the child was measured lying down (<24mo)
--     or standing (>=24mo), not on the height value itself. This schema only
--     stores one row per (sex, height_cm), so we cannot represent both curves
--     at once -- we use the standing/height curve for 65cm+ since that is the
--     more common kiosk measurement. This is a known simplification to clean
--     up later (e.g. by passing age_months into calculate_whz() and querying
--     the correct curve), not a full WHO Anthro replacement.
-- ============================================================================

