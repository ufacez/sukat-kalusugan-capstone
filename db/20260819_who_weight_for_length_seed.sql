-- ============================================================================
-- 20260819_who_weight_for_length_seed.sql
-- Adds who_weight_for_length: the WHO weight-for-RECUMBENT-LENGTH curve
-- (birth to 23 completed months), extracted from the official DOH e-OPT
-- Plus workbook's "Male"/"Female" reference sheets (columns A-E,
-- "WEIGHT-FOR-LENGTH", 45.0-110.0cm, 0.1cm steps).
--
-- WHY THIS MIGRATION EXISTS:
-- who_weight_for_height (added in 20260817_who_growth_reference_seed.sql)
-- only stores the STANDING-height curve (24-60 months). Per that
-- migration's own comment, WHO publishes weight-for-length and
-- weight-for-height as two separate curves that legitimately disagree over
-- the 65-110cm range they both cover, because the correct one depends on
-- whether the child was measured lying down (<24mo) or standing (>=24mo).
-- calculate_whz() previously had no way to pick the length curve at all --
-- every lookup used the height curve, which is wrong for any child under
-- 24 months tall/long enough to be measured at >=65cm.
--
-- calculate_whz() in who_calculator.php now takes $age_months and queries
-- who_weight_for_length for age_months < 24, who_weight_for_height
-- otherwise -- matching the official DOH e-OPT Plus "Nut_StatusTool" sheet
-- cell AD10, which branches the exact same way.
--
-- Source: WHO Child Growth Standards, official z-score tables (L/M/S),
-- https://www.who.int/tools/child-growth-standards/standards
-- (cross-checked against the DOH e-OPT Plus July 2024 workbook's own
-- "Male"/"Female" sheets, which embed the same WHO tables.)
-- ============================================================================

